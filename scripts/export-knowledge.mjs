#!/usr/bin/env node
/**
 * Exports this site's content as the assistant's knowledge base.
 *
 * The assistant in agent/ answers only from its own database — that is the rule
 * that stops it inventing a fee or a document. So whatever the district
 * publishes here has to reach that database, or the chat panel and the pages
 * behind it will tell a resident two different things.
 *
 * This script is the one direction that transfer runs in: content/ is the
 * source of truth, and the assistant's service catalogue is derived from it.
 * It writes a JSON file; `flask import-site-knowledge` on the agent side reads
 * that file, upserts the district and its services, and rebuilds the search
 * vectors.
 *
 *   npm run knowledge:export
 *   docker compose exec agent flask import-site-knowledge
 *
 * Nothing here is generated by a model. Every string written out is one the
 * district already publishes on a page — which is what makes the export safe
 * to re-run after any content change, and what makes the assistant's answers
 * traceable to a page a resident can read for themselves.
 */

import fs from 'node:fs';
import path from 'node:path';

import { audiences, services } from '@/content/services';
import { intro } from '@/content/about';
import { landmarks } from '@/content/landmarks';
import { laws } from '@/content/legal';
import { sections, site } from '@/content/site';
import { transportModes } from '@/content/transport';

const OUT = path.join(process.cwd(), 'agent', 'site_knowledge', 'montazah-thani.json');

/** The district's row in the assistant's database is matched on this name. */
const DISTRICT_NAME = 'حي المنتزه الثانية';
const DISTRICT_ZONE = 'المنتزه الثانية';

/* Words too common in Arabic administrative prose to discriminate between one
   service and another. Dropping them keeps the keyword list a search key
   rather than a copy of the sentence. */
const STOPWORDS = new Set([
  'من',
  'في',
  'على',
  'إلى',
  'عن',
  'أو',
  'و',
  'التي',
  'الذي',
  'هذا',
  'هذه',
  'ذلك',
  'كل',
  'بعد',
  'قبل',
  'عند',
  'مع',
  'ما',
  'لا',
  'أن',
  'إن',
  'به',
  'له',
  'بها',
  'داخل',
  'خلال',
  'حسب',
  'وفق',
  'طبقًا',
  'يجب',
  'يمكن',
  'اللازم',
  'المطلوب',
  'الحي',
]);

/**
 * Significant Arabic terms from a set of passages, de-duplicated.
 *
 * Insertion order is kept rather than sorted, and callers pass the title
 * first: "ترخيص" and "بناء" are what someone actually types, and sorting by
 * length would push exactly those below "الرسومات الهندسية" and out of the cap.
 */
function keywordsFrom(...passages) {
  const seen = new Set();
  for (const passage of passages) {
    for (const raw of String(passage).split(/[^\p{L}\p{N}]+/u)) {
      const word = raw.replace(/^(ال)/u, '');
      if (word.length < 3 || STOPWORDS.has(raw) || STOPWORDS.has(word)) continue;
      seen.add(raw);
      if (seen.size >= 24) return [...seen];
    }
  }
  return [...seen];
}

const label = (audience) => audiences.find((a) => a.id === audience)?.label.ar ?? '';

/* The category the assistant's dashboard groups a service under. The site
   groups by audience, and these are the same three groups written as the
   navigation writes them, rather than the bare noun the filter chip uses. */
const CATEGORY = {
  residents: 'خدمات المواطنين',
  business: 'خدمات الأعمال',
  visitors: 'خدمات الزائرين',
};

/**
 * A statute named the way the service page names it — including the "pending
 * confirmation" caveat where the legal office has not signed the citation off.
 * The page shows that caveat on screen; the assistant must not quietly drop it.
 */
function lawTitle(id) {
  const law = laws.find((entry) => entry.id === id);
  if (!law) return null;
  const cited = [law.name.ar, law.citation.ar].filter(Boolean).join(' ');
  return law.verified ? cited : `${cited} (في انتظار تأكيد الإدارة القانونية)`;
}

/**
 * The service as the assistant will read it back to a caller: what it is, who
 * may apply, where it is filed, and the caveat the page itself carries.
 */
function description(service) {
  const parts = [service.summary.ar];

  if (service.eligibility.ar.length > 0) {
    parts.push(`من يمكنه التقديم: ${service.eligibility.ar.join('؛ ')}.`);
  }
  if (service.channel.ar) {
    parts.push(`مكان التقديم: ${service.channel.ar}.`);
  }

  const cited = service.legal.map(lawTitle).filter(Boolean);
  if (cited.length > 0) {
    parts.push(`السند القانوني: ${cited.join('، ')}.`);
  }
  if (service.external) {
    parts.push(`بوابة إلكترونية ذات صلة: ${service.external.label.ar} — ${service.external.href}.`);
  }

  parts.push(
    'الرسوم والمدد استرشادية وتخضع للوائح المعمول بها — يُرجى التأكد من مقر الحي قبل التقديم.',
  );

  return parts.join(' ');
}

function serviceRecord(service) {
  const aliases = [service.title.en, service.slug.replace(/-/g, ' ')].filter(Boolean);

  return {
    slug: service.slug,
    name: service.title.ar,
    name_en: service.title.en,
    category: CATEGORY[service.audience] ?? label(service.audience),
    /* Left empty on purpose. The site names where an application is filed, not
       which internal department owns it, and the assistant states a blank
       field as "I do not have that" rather than guessing. */
    department: null,
    description: description(service),
    /* The site's fee text is prose ("calculated by area and use"), never a
       number, so it goes in the note and the numeric column stays null. */
    fees: null,
    fees_note: service.fee.ar,
    required_documents: service.documents.ar.join('\n'),
    steps: service.steps.ar.join('\n'),
    duration: service.duration.ar,
    aliases,
    keywords: keywordsFrom(service.title.ar, service.summary.ar, ...service.documents.ar),
    url: `/ar/services/${service.slug}`,
    /* Only the transactions handled at a counter can be booked. A service the
       site sends to a national portal has no counter here to book. */
    is_bookable: !service.external,
  };
}

/**
 * The free-text block the assistant is given about the district itself. It is
 * injected whole into the prompt, so it stays short and factual: what the
 * district is, its sections, its landmarks, how to reach it.
 */
function districtInfo() {
  const landmarkList = landmarks
    .map((landmark) => `${landmark.name.ar} (${landmark.section.ar})`)
    .join('، ');

  const hotlines = site.hotlines.map((h) => `${h.label.ar} ${h.number}`).join('، ');

  const transport = transportModes
    .map((mode) => `${mode.name.ar}: ${mode.detail.ar}`)
    .join(' ');

  return [
    intro.ar.join(' '),
    `الأقسام الإدارية: ${sections.map((s) => s.ar).join('، ')}.`,
    `أبرز المعالم داخل الحي: ${landmarkList}.`,
    `التنقل داخل الحي — ${transport}`,
    `الخطوط الساخنة: ${hotlines}.`,
    `الموقع الرسمي للحي يعرض تفاصيل كل خدمة على /ar/services، والمعالم على /ar/landmarks.`,
  ].join('\n\n');
}

function districtRecord() {
  return {
    name: DISTRICT_NAME,
    zone: DISTRICT_ZONE,
    address: site.address.ar,
    phone: site.phone,
    email: site.email,
    hotline: site.hotlines[0]?.number ?? null,
    working_hours: site.hours.ar,
    coverage: [
      ...sections.map((section) => section.ar),
      ...new Set(landmarks.map((landmark) => landmark.section.ar)),
    ]
      .filter((value, i, all) => all.indexOf(value) === i)
      .join('، '),
    info: districtInfo(),
    description: site.description.ar,
    aliases: ['El Montazah II', 'المنتزه الثانية', 'ثان المنتزه', 'منتزه ثاني'],
    keywords: keywordsFrom(site.description.ar, sections.map((s) => s.ar).join(' ')),
  };
}

const payload = {
  generated_at: new Date().toISOString(),
  source: 'content/ — the district website',
  district: districtRecord(),
  services: services.map(serviceRecord),
};

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, `${JSON.stringify(payload, null, 2)}\n`, 'utf8');

console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
console.log(`  district: ${payload.district.name}`);
console.log(`  services: ${payload.services.length}`);
console.log('\nLoad it into the assistant with:');
console.log('  docker compose exec agent flask import-site-knowledge');
